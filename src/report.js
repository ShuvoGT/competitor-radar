    const title = `<div style="border-top:1px solid ${C.line};margin-top:14px;padding-top:12px;margin-bottom:6px"><span style="font-size:13.5px;font-weight:700;color:${PLATFORM_COLOR[kind] || C.ink}">${esc(plat(kind))}</span> <span style="font-weight:600;color:${C.mut};font-size:11.5px">· ${all.length} post(s) · Today ${today} · Yesterday ${yest}</span></div>`
