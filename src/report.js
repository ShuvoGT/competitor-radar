function esc(s) {
  return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

// Strip garbled bytes (mojibake replacement chars, control chars) and collapse
// whitespace, so no broken text ever reaches the email.
function clean(s) {
  return String(s == null ? '' : s)
    .replace(/�/g, '')
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '')
    .replace(/[ \t]+/g, ' ')
    .replace(/\s*\n\s*/g, ' ')
    .trim()
}

// ---- plain-language explanations -------------------------------------------
// Readers should not have to decode "cta" or "101 added / 47 removed". These
// turn the internal change codes and the raw diff-count placeholder into a
// sentence anyone can act on. A real AI summary is always kept as written.

const KIND_LABEL = {
  cta: 'Call-to-action / button change',
  pricing: 'Pricing or offer change',
  text: 'Website copy change',
  new_ad: 'New ads launched',
  stopped_ad: 'Ads stopped',
  new_product: 'New product or feature',
  feature: 'Feature change',
  activity: 'Market activity',
}
function kindLabel(kind) {
  const k = String(kind || '').toLowerCase().trim()
  return KIND_LABEL[k] || (k ? k.replace(/_/g, ' ') : 'Change')
}

// What each change kind means, one short line — shown under the item when there
// is no AI recommendation to show instead.
const KIND_HINT = {
  cta: 'They changed a call-to-action or button — often a new offer or a push to convert.',
  pricing: 'Their pricing or offer wording changed — worth checking against ours.',
  text: 'Their page copy changed — messaging or positioning may have shifted.',
  new_ad: 'They put new ads live — see the ad section below for the creatives.',
  stopped_ad: 'They stopped running some ads — a campaign may have ended.',
  new_product: 'They may have launched a new product or feature.',
  feature: 'A feature on their page changed.',
  activity: 'General market activity was detected.',
}
function kindHint(kind) {
  return KIND_HINT[String(kind || '').toLowerCase().trim()] || ''
}

// The collector writes a placeholder summary like "101 added / 47 removed (Comp)"
// or "7 new ad(s), 0 stopped (Comp)" until the AI rewrites it. Turn that into a
// readable sentence; keep any real (AI) summary untouched.
function explainChange(c) {
  const raw = clean(c && c.summary)
  const dm = raw.match(/^(\d+)\s*added\s*\/\s*(\d+)\s*removed/i)
  if (dm) {
    const added = Number(dm[1]), removed = Number(dm[2])
    const who = (c && c.competitor) || 'this competitor'
    const what = kindLabel(c && c.kind).toLowerCase()
    return `${who} — ${what}: ${added} line(s) of new text appeared and ${removed} were removed on the watched page. Bigger numbers usually mean a bigger update.`
  }
  const am = raw.match(/^(\d+)\s+new ad\(s\),\s*(\d+)\s+stopped/i)
  if (am) {
    const nw = Number(am[1]), st = Number(am[2])
    const who = (c && c.competitor) || 'This competitor'
    return `${who} launched ${nw} new ad(s)${st ? ` and stopped ${st}` : ''} in this window.`
  }
  return raw   // a genuine AI-written summary — leave it as is
}

// Rough engagement signal from captured post text, where the platform exposes
// it. Reddit gives up-votes and comment counts in the text we scrape; Facebook,
// LinkedIn, Instagram and X do not (we read the page, not their APIs), so most
// posts return nothing here and we rank by our own significance score instead.
function engagementOf(post) {
  const hay = [String((post && post.summary) || ''), ...(((post && post.lines) || []))].join('  ')
  const up = hay.match(/(\d[\d,]*)\s*up\b/i)
  const cm = hay.match(/(\d[\d,]*)\s*comments?\b/i)
  const parts = []
  if (up) parts.push(up[1] + ' upvotes')
  if (cm) parts.push(cm[1] + ' comments')
  const num = (up ? Number(up[1].replace(/,/g, '')) : 0) + (cm ? Number(cm[1].replace(/,/g, '')) : 0)
  return { text: parts.join(' · '), num }
}

// A short "what we can learn / do" line, built only from what the AI analysis
// actually captured. No analysis -> no invented advice.
// Treat "none"-like AI values as empty so a takeaway never reads "They promise: none".
const _blankish = (v) => { const s = String(v || '').trim(); return !s || /^(none|n\/?a|null|প্রযোজ্য\s*নয়|not applicable|unknown)\b/i.test(s) ? '' : s }
function takeawayOf(a) {
  if (!a) return ''
  const angle = _blankish(a.content_angle), obj = _blankish(a.campaign_objective)
  const pain = _blankish(a.pain_point), promise = _blankish(a.value_proposition)
  const bits = []
  if (angle) bits.push('a ' + angle.toLowerCase() + ' angle')
  if (obj) bits.push('to drive ' + obj.toLowerCase())
  if (pain) bits.push('around “' + pain + '”')
  if (!bits.length && !promise) return ''
  const lead = bits.length ? 'They are using ' + bits.join(', ') + '. ' : ''
  const pr = promise ? 'They promise: “' + promise + '”. ' : ''
  return lead + pr + 'Worth matching the format or countering the message in our own content.'
}

// Text that is a login wall, a consent page, a CAPTCHA or a search-result
// placeholder — never an actual post. Used to drop non-posts from the social feed.
const SOCIAL_JUNK_RE = /quick security check|by clicking (continue|agree)|user agreement|privacy policy|cookie policy|microsoft store|don.?t have the app|log ?in to|sign in to|create (a )?new account|forgot password|google\.com\/search|site:instagram\.com|\bcaptcha\b|enable javascript|you.?re not signed in|verify (you are )?human|continue to join|agree & join|by continuing you|unusual traffic|i.?m not a robot/i
function cleanSocialLines(lines) {
  return (lines || []).filter((l) => {
    const t = String(l || '').replace(/\s+/g, ' ').trim()
    return t.length > 12 && !SOCIAL_JUNK_RE.test(t) && !/^url:\s*https?:/i.test(t) && !/^https?:\/\/\S+$/i.test(t)
  })
}

