// Add a scheme to a bare domain so the link works from an email client.
function absUrl(u) {
  const v = String(u || '').trim()
  if (!v) return null
  return /^https?:\/\//i.test(v) ? v : 'https://' + v.replace(/^\/+/, '')
}

function hostOf(u) {
  try { return new URL(absUrl(u)).hostname.replace(/^www\./, '') } catch { return '' }
}

// Is this a search / placeholder URL rather than a real post or profile? Those
// are watched when no real handle is known; the report must not present them as
// "the post", so we drop the link when it is one of these.
function isSearchLink(u) {
  const s = String(u || '')
  if (!s) return true
  return /[?&](q|query|search_query)=/i.test(s)
    || /\/search(\/|\?|$)/i.test(s)
    || /google\.com\/search/i.test(s)
    || /\/ads\/library/i.test(s)
    || /adstransparency\.google\.com\/\?/i.test(s)
}
// Return a real post/profile link, or null for a search/placeholder link.
function realLink(u) { return isSearchLink(u) ? null : absUrl(u) }

// Whether a Facebook post is a video, a reel or a static (image/text) post, read
// from the shape of its permalink: /reel/ is a reel, /videos/ and /watch are
// video, everything else (posts, photos, text) is static.
function fbMediaType(u) {
  const s = String(u || '')
  if (/\/reel\//i.test(s)) return 'Reel'
  if (/\/videos?\/|\/watch/i.test(s)) return 'Video'
  return 'Static'
}
function isVideoType(t) { return t === 'Reel' || t === 'Video' }

// A single ad's permanent page in the Meta Ad Library. ad_key is the Library ID.
function adUrl(ad) {
  if (!ad) return null
  if (ad.platform === 'meta' && ad.ad_key) return 'https://www.facebook.com/ads/library/?id=' + encodeURIComponent(ad.ad_key)
  // Google Ads Transparency does not expose ad copy — only a creative link.
  if (ad.platform === 'google') return (ad.raw && ad.raw.creativeLink) || absUrl(ad.source_url)
  return absUrl(ad.source_url)
}

// The library/transparency page an advertiser's ads were collected from.
// Prefers the exact URL being watched; falls back to a keyword search.
function advertiserUrl(row) {
  if (row && row.source_url) return absUrl(row.source_url)
  const name = String((row && row.competitor) || '').trim()
  if (!name) return null
  return row.platform === 'google'
    ? 'https://adstransparency.google.com/?region=anywhere&query=' + encodeURIComponent(name)
    : 'https://www.facebook.com/ads/library/?active_status=all&ad_type=all&country=ALL&search_type=keyword_unordered&q=' + encodeURIComponent(name)
}

// Normalise a DB timestamp to an ISO string. node-pg hands back a Date, and
// String(Date) ("Thu Sep 24 2026 …") then renders as " hu Sep 24 2026" in the
// report's T-replace formatting. ISO keeps every shown date correct.
function iso(ts) {
  if (!ts) return null
  try { return new Date(ts).toISOString() } catch { return null }
}

async function buildData({ days = 1 } = {}) {
  // A daily report should cover BOTH yesterday and today so counts can be split
  // by day. So the window is at least 2 days; a weekly report keeps its 7.
  const win = Math.max(Number(days) || 1, 2)
  const OFF = 6 * 3600000  // Asia/Dhaka (GMT+6)
  const end = new Date(Date.now() + OFF).toISOString().slice(0, 10)
  const start = new Date(Date.now() + OFF - win * 86400000).toISOString().slice(0, 10)
  const todayStr = end
  const yestStr = new Date(Date.now() + OFF - 86400000).toISOString().slice(0, 10)
  const dayOf = (ts) => { try { return new Date(new Date(ts).getTime() + OFF).toISOString().slice(0, 10) } catch { return '' } }
  const dayBucket = (ts) => { const d = dayOf(ts); return d === todayStr ? 'today' : d === yestStr ? 'yesterday' : 'older' }

  // source_url falls back to the competitor's own watched page when a change
  // has no source row of its own, so every change can still link somewhere real.
  const changes = (await q(`
    SELECT c.*, s.kind AS source_kind,
           COALESCE(s.url, (
             SELECT w.url FROM radar_sources w
             WHERE w.competitor = c.competitor AND w.active
             ORDER BY (w.kind = 'website') DESC, (w.kind = 'blog') DESC,
                      (w.kind = 'pricing') DESC, w.id
             LIMIT 1
           )) AS source_url
    FROM radar_changes c LEFT JOIN radar_sources s ON s.id = c.source_id
    WHERE c.detected_at > now() - ($1::int * interval '1 day')
      AND COALESCE(s.kind, '') <> 'review'
    ORDER BY c.score DESC, c.detected_at DESC`, [win])).rows || []
  // Per advertiser: total, active, newly launched and recently stopped ads, plus
  // the library page they are watched on.
  const ads = (await q(`
    SELECT a.platform, a.competitor, count(*) FILTER (WHERE a.active)::int AS ads,
           count(*) FILTER (WHERE a.active)::int AS active,
           count(*) FILTER (WHERE a.first_seen > now() - ($1::int * interval '1 day') AND NOT a.baseline)::int AS new_ads,
           count(*) FILTER (WHERE NOT a.active AND a.last_seen > now() - ($1::int * interval '1 day'))::int AS stopped_ads,
           max(s.url) AS source_url
    FROM radar_ads a
    LEFT JOIN radar_sources s
      ON s.competitor = a.competitor
     AND s.kind = CASE WHEN a.platform = 'google' THEN 'google_ads' ELSE 'meta_adlib' END
    GROUP BY 1,2 ORDER BY new_ads DESC, stopped_ads DESC, ads DESC`, [win])).rows || []
  const mentions = (await q(`
    SELECT keyword, sentiment, count(*)::int AS n
    FROM radar_mentions WHERE found_at > now() - ($1::int * interval '1 day')
    GROUP BY 1,2 ORDER BY n DESC`, [win])).rows || []
  const topMentions = (await q(`
    SELECT keyword, platform, url, text, sentiment, found_at
    FROM radar_mentions WHERE found_at > now() - ($1::int * interval '1 day')
      AND sentiment IN ('negative','positive')
    ORDER BY found_at DESC LIMIT 15`, [win])).rows || []
  const newAdsList = (await q(`
    SELECT a.platform, a.competitor, a.product, a.ad_key, a.page_name, a.copy, a.headline, a.cta, a.offer,
           a.landing_url, a.format, a.started_running, a.active, a.first_seen, a.raw,
           s.url AS source_url
    FROM radar_ads a
    LEFT JOIN radar_sources s
      ON s.competitor = a.competitor
     AND s.kind = CASE WHEN a.platform = 'google' THEN 'google_ads' ELSE 'meta_adlib' END
    WHERE a.first_seen > now() - ($1::int * interval '1 day')
      AND NOT a.baseline
     ORDER BY (a.platform = 'google') ASC, a.first_seen DESC LIMIT 15`, [win])).rows || []
  // Ads that were running before and have since vanished from the library.
  const stoppedAdsList = (await q(`
    SELECT a.platform, a.competitor, a.product, a.ad_key, a.page_name, a.copy, a.headline, a.cta, a.offer,
           a.landing_url, a.format, a.started_running, a.active, a.first_seen, a.last_seen, a.raw,
           s.url AS source_url
    FROM radar_ads a
    LEFT JOIN radar_sources s
      ON s.competitor = a.competitor
     AND s.kind = CASE WHEN a.platform = 'google' THEN 'google_ads' ELSE 'meta_adlib' END
    WHERE NOT a.active AND a.last_seen > now() - ($1::int * interval '1 day')
    ORDER BY a.last_seen DESC LIMIT 10`, [win])).rows || []
  const stoppedAdKeys = new Set(stoppedAdsList.map((a) => a.platform + '|' + a.ad_key))
  // Every ad that is running right now, with full detail.
  const activeAdsList = (await q(`
    SELECT a.platform, a.competitor, a.product, a.ad_key, a.page_name, a.copy, a.headline, a.cta, a.offer,
           a.landing_url, a.format, a.started_running, a.active, a.first_seen, a.raw,
           s.url AS source_url
    FROM radar_ads a
    LEFT JOIN radar_sources s
      ON s.competitor = a.competitor
     AND s.kind = CASE WHEN a.platform = 'google' THEN 'google_ads' ELSE 'meta_adlib' END
    WHERE a.active
    ORDER BY (a.platform = 'google') ASC, a.competitor, a.first_seen DESC LIMIT 16`)).rows || []

  // Social coverage: every watched social profile, and whether it was captured.
  const socialSources = (await q(`
    SELECT s.id, s.competitor, s.product, s.kind, s.url,
           (SELECT max(x.captured_at) FROM radar_snapshots x WHERE x.source_id = s.id AND x.status = 'ok') AS last_ok,
           (SELECT x.captured_at FROM radar_snapshots x WHERE x.source_id = s.id ORDER BY x.captured_at DESC LIMIT 1) AS last_try,
           (SELECT x.error FROM radar_snapshots x WHERE x.source_id = s.id ORDER BY x.captured_at DESC LIMIT 1) AS last_error
    FROM radar_sources s
    WHERE s.active AND s.competitor <> 'BRAND' AND s.kind = ANY($1::text[])
    ORDER BY s.competitor, s.kind`, [SOCIAL_KINDS])).rows || []

  // Social activity: what actually changed on those profiles in this window.
  const socialChanges = (await q(`
    SELECT c.id, c.competitor, c.product, s.kind, s.url, c.score, c.severity, c.summary,
           c.detected_at, c.diff, c.analysis
    FROM radar_changes c JOIN radar_sources s ON s.id = c.source_id
    WHERE c.detected_at > now() - ($1::int * interval '1 day')
      AND s.kind = ANY($2::text[])
    ORDER BY c.score DESC, c.detected_at DESC LIMIT 120`, [win, SOCIAL_KINDS])).rows || []

  const socialMap = new Map()
  const ensure = (name, product) => {
    const k = name || '?'
    if (!socialMap.has(k)) socialMap.set(k, { competitor: k, product: product || '', platforms: [], posts: [], activity: 0 })
    return socialMap.get(k)
  }
  for (const src of socialSources) {
    const g = ensure(src.competitor, src.product)
    g.platforms.push({
      kind: src.kind, url: src.url, posts: 0,
      lastOk: src.last_ok, lastTry: src.last_try,
      error: src.last_ok ? null : (src.last_error || 'never captured'),
    })
  }
  const platformTally = new Map()
  // Captured Facebook posts — used ONLY to attach a real permalink (and its
  // reaction/comment/share counts) to a page-diff post when their text matches.
  // The page-diff is the RELIABLE source of the post content; the capture just
  // supplies the exact link where it has one. Junk captures (the page's own
  // name / intro block) never match a real post, so they attach nothing.
  let fbCaptured = []
  try {
    fbCaptured = (await q(
      `SELECT competitor, url, text, reactions, comments, shares, engagement,
              posted_at, first_seen, last_seen
       FROM radar_social_posts WHERE platform = 'facebook'
         AND COALESCE(posted_at, first_seen) > now() - interval '45 day'
       ORDER BY COALESCE(posted_at, first_seen) DESC LIMIT 400`)).rows || []
  } catch { /* radar_social_posts not created yet — skip until schema is applied */ }
  const fbByComp = new Map()
  for (const r of fbCaptured) { const k = r.competitor || '?'; if (!fbByComp.has(k)) fbByComp.set(k, []); fbByComp.get(k).push(r) }
  const fbNorm = (s) => String(s || '').toLowerCase().replace(/[^\p{L}\p{N}]/gu, '')
  const matchFb = (competitor, text) => {
    const list = fbByComp.get(competitor || '?') || []
    const t = fbNorm(text)
    if (t.length < 12) return null
    for (const r of list) {
      const rt = fbNorm(r.text)
      if (!rt || rt.length < 12) continue
      const shorter = t.length <= rt.length ? t : rt
      const longer = t.length <= rt.length ? rt : t
      const w = Math.min(25, shorter.length)
      for (let i = 0; i + w <= shorter.length; i += 8) {
        if (longer.includes(shorter.slice(i, i + w))) return r
      }
    }
    return null
  }

  for (const c of socialChanges) {
    const g = ensure(c.competitor, c.product)
    // Only real posts count. Login walls, consent pages, CAPTCHAs, search
    // placeholders and empty diffs are recorded as a capture ISSUE, not a post.
    const _raw = postLines(c.diff)
    const _lines = cleanSocialLines(_raw)
    if (!_lines.length) {
      const reason = isSearchLink(c.url) ? 'no real profile connected (watching a search page)'
        : SOCIAL_JUNK_RE.test(_raw.join(' ')) ? 'login wall — sign the capture browser in'
        : 'page changed but no readable post text'
      g.issues = g.issues || {}
      if (!g.issues[c.kind]) g.issues[c.kind] = reason
      continue
    }
    g.activity++
    platformTally.set(c.kind, (platformTally.get(c.kind) || 0) + 1)
    const p = g.platforms.find((x) => x.kind === c.kind && x.url === c.url)
    if (p) p.posts++
    const _post = { summary: c.summary, lines: _lines }
    // For Facebook, attach the exact permalink + real counts of the matching
    // captured post when we have one. Content stays the reliable page-diff text.
    const _fb = c.kind === 'facebook' ? matchFb(c.competitor, `${_lines.join(' ')} ${c.summary || ''}`) : null
    const _fbBits = []
    if (_fb) {
      if (_fb.reactions != null) _fbBits.push(_fb.reactions + ' reactions')
      if (_fb.comments != null) _fbBits.push(_fb.comments + ' comments')
      if (_fb.shares != null) _fbBits.push(_fb.shares + ' shares')
    }
    g.posts.push({
      kind: c.kind, url: c.url,
      link: _fb ? _fb.url : (c.kind === 'facebook' ? realLink(c.url) : null), exact: Boolean(_fb),
      mediaType: c.kind === 'facebook' ? fbMediaType(_fb ? _fb.url : '') : undefined,
      day: dayBucket(c.detected_at),
      when: iso(c.detected_at), score: c.score, severity: c.severity,
      summary: c.summary, lines: _lines,
      angle: (c.analysis || {}).content_angle || null,
      cta: (c.analysis || {}).cta && (c.analysis || {}).cta !== 'none' ? (c.analysis || {}).cta : null,
      objective: (c.analysis || {}).campaign_objective || null,
      analysis: c.analysis || null,
      engagement: _fb ? { text: _fbBits.join(' · '), num: Number(_fb.engagement || 0) } : engagementOf(_post),
      takeaway: takeawayOf(c.analysis),
    })
  }
  // Replace page-snapshot YouTube "posts" (no real link) with actual videos from
  // the channel feed — each with an EXACT watch link, title and publish date.
  let ytVideos = []
  try {
    ytVideos = (await q(
      `SELECT competitor, title, url, published FROM radar_articles
       WHERE kind = 'youtube' AND published IS NOT NULL AND published > now() - ($1::int * interval '1 day')
       ORDER BY published DESC LIMIT 40`, [win])).rows || []
  } catch { /* table not created yet */ }
  for (const g of socialMap.values()) g.posts = g.posts.filter((p) => p.kind !== 'youtube')
  for (const v of ytVideos) {
    const g = ensure(v.competitor, '')
    g.activity++
    platformTally.set('youtube', (platformTally.get('youtube') || 0) + 1)
    g.posts.push({
      kind: 'youtube', url: v.url, link: v.url, exact: true, day: dayBucket(v.published),
      when: iso(v.published), score: 55, severity: null, summary: v.title, lines: [v.title],
      angle: null, cta: null, objective: null, analysis: null, mediaType: 'Video',
      engagement: { text: '', num: 0 }, takeaway: '',
    })
  }

  // One post = one card. The page diff can record the same post as "changed" on
  // several scans, which repeats it. Collapse per competitor by the post text,
  // keeping the linked (exact) variant when there is one.
  for (const g of socialMap.values()) {
    const sorted = g.posts.slice().sort((a, b) => (b.exact ? 1 : 0) - (a.exact ? 1 : 0) || (b.score || 0) - (a.score || 0))
    const seen = new Set()
    g.posts = sorted.filter((p) => {
      const key = String((p.lines || []).join(' ')).replace(/\s+/g, ' ').trim().toLowerCase().slice(0, 80) || String(p.link || p.url || '')
      if (seen.has(key)) return false
      seen.add(key)
      return true
    })
    g.activity = g.posts.length
  }
  // Rebuild the per-platform tally from the deduped posts so the counts match.
  platformTally.clear()
  for (const g of socialMap.values()) for (const p of g.posts) platformTally.set(p.kind, (platformTally.get(p.kind) || 0) + 1)

  const socialGroups = [...socialMap.values()]
    .map((g) => ({ ...g, posts: g.posts.sort((a, b) => (b.score || 0) - (a.score || 0)) }))
    .sort((a, b) => b.activity - a.activity || a.competitor.localeCompare(b.competitor))
  const socialGaps = socialSources.filter((x) => !x.last_ok)
    .map((x) => ({ competitor: x.competitor, kind: x.kind, url: x.url, error: x.last_error || 'never captured' }))
  const allSocialPosts = socialGroups.flatMap((g) => g.posts)
  // Collapse per-competitor capture issues into one list, deduped by platform+reason.
  const captureIssues = []
  const seenIssue = new Set()
  for (const g of socialGroups) {
    for (const [kind, reason] of Object.entries(g.issues || {})) {
      const key = kind + '|' + reason
      if (seenIssue.has(key)) continue
      seenIssue.add(key)
      captureIssues.push({ kind, reason })
    }
  }
  const social = {
    groups: socialGroups,
    byPlatform: [...platformTally.entries()].map(([kind, count]) => ({ kind, count })).sort((a, b) => b.count - a.count),
    totals: {
      profiles: socialSources.length,
      captured: socialSources.filter((x) => x.last_ok).length,
      posts: allSocialPosts.length,
      today: allSocialPosts.filter((p) => p.day === 'today').length,
      yesterday: allSocialPosts.filter((p) => p.day === 'yesterday').length,
      activeCompetitors: socialGroups.filter((g) => g.activity > 0).length,
    },
    captureIssues,
    gaps: socialGaps,
  }

  const sev = { critical: 0, high: 0, medium: 0, low: 0 }
  for (const c of changes) if (sev[c.severity] != null) sev[c.severity]++

  const byComp = new Map()
  for (const c of changes) {
    const k = c.competitor || '?'
    if (!byComp.has(k)) byComp.set(k, { name: k, product: c.product || '', changes: 0, maxScore: 0, threat: 'low' })
    const b = byComp.get(k)
    b.changes++
    if (Number(c.score) > b.maxScore) { b.maxScore = Number(c.score) || 0; b.threat = c.severity || 'low' }
  }
  const competitors = [...byComp.values()].sort((a, b) => b.maxScore - a.maxScore)
  // "Needs your decision" is NOT a copy of every change — that only duplicates
  // the Website and Social sections below. It carries two things only:
  //   1. clear market moves (new / stopped ads, a new product), and
  //   2. anything the AI has written an actual recommendation (করণীয়) for.
  // Website copy / pricing / CTA page diffs with no recommendation stay in the
  // Website section where their detail belongs. No competitor floods the list.
  const MARKET_MOVES = new Set(['new_ad', 'stopped_ad', 'new_product'])
  const hasRec = (c) => Boolean(c.recommended && String(c.recommended).trim())
  const perComp = new Map()
  const threats = []
  for (const c of changes) {
    if (c.severity !== 'critical' && c.severity !== 'high') continue
    if (!MARKET_MOVES.has(c.kind) && !hasRec(c)) continue   // detail lives in its own section
    const n = perComp.get(c.competitor) || 0
    if (n >= 2) continue
    perComp.set(c.competitor, n + 1)
    threats.push({
      competitor: c.competitor, product: c.product, kind: c.kind, severity: c.severity,
      score: c.score, summary: c.summary, recommended: c.recommended, url: c.source_url,
      lines: postLines(c.diff, 3), analysis: c.analysis,
    })
    if (threats.length >= 12) break
  }

  const tally = (fn) => {
    const m = new Map()
    for (const c of changes) { const v = fn(c); if (v) m.set(v, (m.get(v) || 0) + 1) }
    return [...m.entries()].map(([label, count]) => ({ label, count })).sort((a, b) => b.count - a.count)
  }
  const actions = [...new Set(changes.map((c) => c.recommended).filter(Boolean))].slice(0, 8)
  const mentTotals = { positive: 0, negative: 0, neutral: 0, total: 0 }
  for (const m of mentions) { mentTotals[m.sentiment] = (mentTotals[m.sentiment] || 0) + m.n; mentTotals.total += m.n }

  // Actual blog / newsletter posts published in the window (real titles + dates),
  // read from each site's WordPress REST API or RSS feed during the scan.
  let articleRows = []
  try {
    articleRows = (await q(
      `SELECT competitor, kind, title, url, published, summary
       FROM radar_articles
       WHERE kind IN ('blog','newsletter') AND published IS NOT NULL
         AND published > now() - ($1::int * interval '1 day')
       ORDER BY published DESC LIMIT 60`, [win])).rows || []
  } catch { /* radar_articles not created yet — skip until schema is applied */ }
  const articles = articleRows.map((a) => ({
    competitor: a.competitor, kind: a.kind, title: a.title, url: a.url,
    published: iso(a.published), day: dayBucket(a.published), summary: a.summary,
  }))

  // Brand-new pages created on competitor websites in this window (sitemap-based
  // detection) — reported with their title, summary and link.
  let newPages = []
  try {
    newPages = ((await q(
      `SELECT competitor, url, title, summary, first_seen
       FROM radar_pages
       WHERE baseline = false AND first_seen > now() - ($1::int * interval '1 day')
       ORDER BY first_seen DESC LIMIT 40`, [win])).rows || []).map((p) => ({
      competitor: p.competitor, url: p.url, title: p.title, summary: p.summary,
      when: iso(p.first_seen), day: dayBucket(p.first_seen),
    }))
  } catch { /* radar_pages not created yet — skip until schema is applied */ }

  return {
    period: { start, end, days: win, today: todayStr, yesterday: yestStr },
    kpis: {
      changes: changes.length, ...sev,
      competitors: competitors.length,
      newAds: ads.reduce((a, b) => a + (b.new_ads || 0), 0),
      stoppedAds: ads.reduce((a, b) => a + (b.stopped_ads || 0), 0),
      totalAds: ads.reduce((a, b) => a + (b.ads || 0), 0),
      mentions: mentTotals.total, negativeMentions: mentTotals.negative || 0,
      socialPosts: social.totals.posts, socialToday: social.totals.today, socialYesterday: social.totals.yesterday,
      socialProfiles: social.totals.profiles, socialCaptured: social.totals.captured,
      postsPublished: articles.length,
      analyzed: changes.filter((c) => c.analysis).length,
    },
    competitors, threats, ads, mentions, mentTotals, topMentions, newAdsList, activeAdsList, stoppedAdsList, social, articles, newPages,
    painPoints: tally((c) => (c.analysis || {}).pain_point),
    angles: tally((c) => (c.analysis || {}).content_angle),
    ctas: tally((c) => { const v = (c.analysis || {}).cta; return v && v !== 'none' ? v : null }),
    actions,
    changes: changes.slice(0, 80).map((c) => ({ competitor: c.competitor, kind: c.kind, severity: c.severity, score: c.score, summary: c.summary, when: iso(c.detected_at), day: dayBucket(c.detected_at), url: c.source_url, sourceKind: c.source_kind, lines: postLines(c.diff, 3), analysis: c.analysis || null, takeaway: takeawayOf(c.analysis) })),
    // Website/content changes taken from the FULL change set (not the 80-item
    // slice above), so blog/newsletter/pricing moves are never buried under the
    // volume of social posts.
    webChanges: changes
      .filter((c) => ['website', 'blog', 'pricing', 'landing', 'product', 'newsletter'].includes(String(c.source_kind || '').toLowerCase()))
      .map((c) => ({ competitor: c.competitor, sourceKind: c.source_kind, kind: c.kind, severity: c.severity, score: c.score, summary: c.summary, when: iso(c.detected_at), day: dayBucket(c.detected_at), url: c.source_url, lines: postLines(c.diff, 4), analysis: c.analysis || null, takeaway: takeawayOf(c.analysis) })),
  }
}

function renderMarkdown(d) {
  const L = []
  L.push(`# ${d.period.days <= 1 ? BN.dailyTitle : BN.title}`)
  L.push(`**${BN.period}:** ${d.period.start} → ${d.period.end}  (${d.period.days} ${BN.days})`)
  L.push('')
  L.push(`## ${BN.summary}`)
  L.push(`- **${d.kpis.changes} ${BN.changes}** · **${d.kpis.competitors} ${BN.competitors}** · **${d.kpis.newAds} ${BN.newAds}**`)
  L.push(`- ${BN.critical} ${d.kpis.critical} · ${BN.high} ${d.kpis.high} · ${BN.medium} ${d.kpis.medium} · ${BN.low} ${d.kpis.low}`)
  L.push(`- ${BN.brand}: ${d.kpis.mentions} mention(s) — ${d.mentTotals.negative || 0} negative`)
  L.push('')
  if (d.threats.length) {
    L.push(`## ${BN.threats}`)
    L.push(`_Score is urgency out of 100 (higher = act sooner). "Type" is the kind of move. "What happened" explains the change in plain words._`)
    L.push('')
    L.push(`| ${BN.competitor} | ${BN.type} | ${BN.severity} | ${BN.score} | ${BN.what} | ${BN.recommended} | Source |`)
    L.push('|---|---|---|---|---|---|---|')
    for (const t of d.threats) L.push(`| ${t.competitor || '—'} | ${kindLabel(t.kind)} | ${t.severity} | ${t.score ?? '—'} | ${String(explainChange(t)).replace(/\|/g, '/')} | ${String(t.recommended || (kindHint(t.kind) ? kindHint(t.kind) + ' (no AI recommendation yet)' : '')).replace(/\|/g, '/')} | ${t.url ? `[${hostOf(t.url) || 'open'}](${absUrl(t.url)})` : '—'} |`)
    L.push('')
  }
  // Ad intelligence — Google and Meta
  L.push(`## ${BN.ads}`)
  const gAds = d.ads.filter((a) => a.platform === 'google')
  const mAds = d.ads.filter((a) => a.platform === 'meta')
  const adBlock = (title, rows, emptyMsg) => {
    L.push(`### ${title}`)
    if (!rows.length) { L.push(emptyMsg); L.push(''); return }
    L.push(`| ${BN.competitor} | ${BN.activeAds} | ${BN.newAds} | Source |`)
    L.push('|---|---|---|---|')
    for (const a of rows) { const u = advertiserUrl(a); L.push(`| ${a.competitor || '—'} | ${a.active} | ${a.new_ads} | ${u ? `[${a.platform === 'google' ? 'Transparency Center' : 'Ad Library'}](${u})` : '—'} |`) }
    L.push('')
  }
  adBlock('Meta Ads', mAds, 'No Meta ad activity in this window.')
  adBlock('Google Ads', gAds, 'No Google ad activity in this window.')
  if ((d.newAdsList || []).length) {
    L.push(`### New ads in detail${d.kpis.newAds > d.newAdsList.length ? ` — showing ${d.newAdsList.length} of ${d.kpis.newAds} (rest on the dashboard)` : ''}`)
    for (const a of d.newAdsList) {
      const exactAd = adUrl(a)
      const u = exactAd || advertiserUrl(a)
      L.push(`- **${a.competitor || '—'}** (${a.platform}${a.active ? ', active' : ', stopped'})${a.cta ? ` · CTA: ${a.cta}` : ''}${a.offer ? ` · Offer: ${a.offer}` : ''}`)
      const copy = clean(a.copy).slice(0, 240)
      if (copy) L.push(`  - ${copy}`)
      if (u) L.push(`  - ${exactAd ? 'Ad' : 'Source'}: ${u}${a.ad_key ? ` (Library ID ${a.ad_key})` : ''}`)
      if (a.landing_url) L.push(`  - Landing page: ${absUrl(a.landing_url)}`)
    }
    L.push('')
  }

  // Social media activity — one block per platform
  const so = d.social || { groups: [], byPlatform: [], totals: {}, gaps: [] }
  const postsByPlat = {}, gapByPlat = {}
  for (const g of (so.groups || [])) {
    for (const p of (g.posts || [])) { (postsByPlat[p.kind] = postsByPlat[p.kind] || []).push({ ...p, competitor: g.competitor }) }
    for (const pf of (g.platforms || [])) { if (pf.error) gapByPlat[pf.kind] = (gapByPlat[pf.kind] || 0) + 1 }
  }
  L.push(`## Social Media Activity`)
  L.push(`Read ${d.kpis.socialCaptured || 0} of ${d.kpis.socialProfiles || 0} watched social profiles this window. An empty platform can mean it was quiet or could not be read. Login-walled profiles need the capture browser signed in; name-search placeholders need the real profile connected.`)
  L.push('')
  const platBlock = (kind) => {
    const label = PLATFORM_LABEL[kind] || kind
    L.push(`### ${label}`)
    const posts = (postsByPlat[kind] || []).slice().sort((a, b) => (b.score || 0) - (a.score || 0)).slice(0, 8)
    if (!posts.length) {
      const gap = gapByPlat[kind] || 0
      L.push(gap ? `No new ${label} posts captured in this window. ${gap} profile(s) could not be read, usually a login wall.` : `No new ${label} activity in this window.`)
      L.push('')
      return
    }
    for (const p of posts) {
      L.push(`- **${p.competitor}** · ${String(p.when || '').slice(0, 16).replace('T', ' ')}${p.mediaType ? ` · ${isVideoType(p.mediaType) ? '🎬' : ''}${p.mediaType}` : ''}`)
      if ((p.lines || []).length) for (const l of p.lines) L.push(`  - ${clean(l)}`)
      else if (p.summary) L.push(`  - ${clean(p.summary)}`)
      if (p.link) L.push(`  - ${p.exact && p.kind === 'youtube' ? 'Watch' : 'Post'}: ${absUrl(p.link)}`)
    }
    L.push('')
  }
  for (const k of ['facebook', 'linkedin', 'quora', 'youtube']) platBlock(k)
  for (const k of ['x', 'instagram', 'reddit', 'tiktok', 'threads', 'pinterest']) if ((postsByPlat[k] || []).length) platBlock(k)

  // Website activity — published blog/newsletter posts (real, from the feed),
  // then page changes for the rest of the site (blog/newsletter excluded so we
  // never show the raw blog-endpoint diff).
  const WEB_KINDS = ['website', 'pricing', 'landing', 'product']
  const webChanges = (d.changes || []).filter((c) => WEB_KINDS.includes(String(c.sourceKind || '').toLowerCase()))
  const arts = d.articles || []
  L.push(`## Website Activity`)
  L.push(`### Published posts`)
  if (arts.length) {
    for (const a of arts) L.push(`- **${a.competitor || '—'}** · ${a.kind === 'newsletter' ? 'Newsletter' : 'Blog'} · ${String(a.published || '').slice(0, 10)}${a.day ? ` (${a.day})` : ''} — ${clean(a.title)}${a.url ? `\n  - ${absUrl(a.url)}` : ''}`)
  } else {
    L.push('No blog or newsletter posts were published today or yesterday.')
  }
  L.push('')
  L.push(`### New pages`)
  const _np = d.newPages || []
  if (_np.length) {
    for (const p of _np) L.push(`- **${p.competitor || '—'}** · new page${p.day ? ` (${p.day})` : ''} — ${clean(p.title || p.url)}${p.summary ? `\n  - ${clean(String(p.summary).slice(0, 240))}` : ''}${p.url ? `\n  - ${absUrl(p.url)}` : ''}`)
  } else {
    L.push('No brand-new pages were created on competitor websites in this window.')
  }
  L.push('')
  L.push(`### Site changes`)
  if (!webChanges.length) {
    L.push('No website, pricing, landing page or product page changes were detected in this window.')
    L.push('')
  } else {
    for (const c of webChanges.slice(0, 30)) L.push(`- ${String(c.when || '').slice(0, 10)} · **${c.competitor || '—'}** · ${c.sourceKind || 'website'} — ${clean(explainChange(c))}${realLink(c.url) ? `\n  - Source: ${absUrl(c.url)}` : ''}`)
    L.push('')
  }

  // Brand monitoring
  L.push(`## ${BN.brand}`)
  if (d.topMentions.length) {
    for (const m of d.topMentions) L.push(`- [${m.sentiment}] **${m.keyword}** (${m.platform}) — ${clean(m.text).slice(0, 160)}\n  - ${m.url ? `Source: ${absUrl(m.url)}` : 'No link was captured for this mention.'}`)
  } else {
    L.push('No positive or negative brand mentions in this window.')
  }
  L.push('')

  if (d.actions.length) { L.push(`## ${BN.actions}`); for (const a of d.actions) L.push(`- ${clean(a)}`);     L.push('')
  }
  if ((d.stoppedAdsList || []).length) {
    L.push(`### Stopped ads in detail${d.kpis.stoppedAds > d.stoppedAdsList.length ? ` — showing ${d.stoppedAdsList.length} of ${d.kpis.stoppedAds} (rest on the dashboard)` : ''}`)
    for (const a of d.stoppedAdsList) {
      const u = adUrl(a) || advertiserUrl(a)
      L.push(`- **${a.competitor || '—'}** (${a.platform}, stopped)${a.cta ? ` · CTA: ${a.cta}` : ''}`)
      const copy = clean(a.copy).slice(0, 240)
      if (copy) L.push(`  - ${copy}`)
      if (u) L.push(`  - Ad: ${u}${a.ad_key ? ` (Library ID ${a.ad_key})` : ''}`)
    }
    L.push('')
  }
  if ((d.activeAdsList || []).length) {
    L.push(`### Running ads in detail${d.kpis.totalAds > d.activeAdsList.length ? ` — showing ${d.activeAdsList.length} of ${d.kpis.totalAds} (rest on the dashboard)` : ''}`)
    for (const a of d.activeAdsList) {
      const u = adUrl(a) || advertiserUrl(a)
      L.push(`- **${a.competitor || '—'}** (${a.platform}, running)${a.cta ? ` · CTA: ${a.cta}` : ''}${a.format ? ` · ${a.format}` : ''}`)
      const copy = clean(a.copy).slice(0, 240)
      if (copy) L.push(`  - ${copy}`)
      if (u) L.push(`  - Ad: ${u}${a.ad_key ? ` (Library ID ${a.ad_key})` : ''}`)
      if (a.landing_url) L.push(`  - Landing page: ${absUrl(a.landing_url)}`)
    }
    L.push('')
  }
  return L.join('\n')
}

