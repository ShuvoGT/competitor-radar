// Page furniture that every social capture picks up. It is not a post.
const CHROME_RE = /^(home|about|photos|videos|reels|posts|more|menu|log ?in|sign ?up|follow|following|followers|likes?|share|comment|see more|see all|show more|load more|privacy|terms|cookies|advertis\w*|help|settings|english|search|create|notifications|messages|explore|subscribe|subscribed|join|sort by|new|top|hot|save|report|translate)\b/i

// The genuinely new lines on a social page in this window — in practice, the
// text of new posts. Short fragments and navigation are dropped.
function postLines(diff, max = 4) {
  const added = (diff && Array.isArray(diff.added)) ? diff.added : []
  const seen = new Set()
  const out = []
  for (const raw of added) {
    const line = String(raw || '').replace(/\s+/g, ' ').trim()
    if (line.length < 30 || line.length > 600) continue
    if (CHROME_RE.test(line)) continue
    if (!/[a-z\u0980-\u09FF]{4}/i.test(line)) continue          // needs real words (Latin or Bangla)
    const key = line.slice(0, 60).toLowerCase()
    if (seen.has(key)) continue
    seen.add(key)
    out.push(line.length > 320 ? line.slice(0, 320) + '…' : line)
    if (out.length >= max) break
  }
  return out
}

